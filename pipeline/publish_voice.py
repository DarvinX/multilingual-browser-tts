"""Publish measured voice variants with the matching dataset citation."""

import argparse
import json
from pathlib import Path
import shutil

from huggingface_hub import HfApi


def collect(release, dataset_commit, frontend, candidates, dest):
    info = json.loads((release / "source.json").read_text())
    dataset = dataset_commit.split("/commit/", 1)[0]
    dest.mkdir(parents=True, exist_ok=True)
    api = HfApi()
    api.dataset_info(dataset.removeprefix("https://huggingface.co/datasets/"))
    name, language = info["language_name"], info["language"]
    variants = []
    for candidate in candidates:
        report = json.loads((candidate / "browser/size.json").read_text())
        validation = json.loads((candidate / "validation/mos.json").read_text())
        test = json.loads((candidate / "test/mos.json").read_text())
        cer = json.loads((candidate / "test/cer.json").read_text())
        if report["model_bytes"] < 1000000 and min(validation["predicted_mos"], test["predicted_mos"]) >= 2.25:
            variants.append((candidate, report, validation, test, cer))
    if not variants:
        raise ValueError(f"No {name} variant meets the compact size and quality gates")
    variants.sort(key=lambda row: (-row[3]["predicted_mos"], row[1]["model_bytes"]))
    shutil.copy2(variants[0][0] / "checkpoint-fp32.pt", dest / "checkpoint-fp32.pt")
    variant_lines = []
    for candidate, sizes, validation, test, cer in variants:
        mode = candidate.name
        path = dest / mode
        browser = path / "browser"
        browser.mkdir(parents=True, exist_ok=True)
        files = ("voice.onnx.gz", "model.weights.gz", "frontend.json.gz", "g2p-encode.onnx.gz", "g2p-decode.onnx.gz", "weight-shuffle.js", "size.json")
        for filename in files:
            shutil.copy2(candidate / "browser" / filename, browser / filename)
        shutil.copy2(candidate / "checkpoint.pt.gz", path)
        for split in ("validation", "test"):
            (path / split).mkdir(exist_ok=True)
            shutil.copy2(candidate / split / "mos.json", path / split)
        shutil.copy2(candidate / "test/cer.json", path / "test")
        variant_lines.append(f"| {mode.upper()} | {sizes['model_bytes']:,} | {validation['predicted_mos']:.3f} | {test['predicted_mos']:.3f} | {cer['cer']:.2%} |")
    (dest / "frontend").mkdir(exist_ok=True)
    for filename in ("phonemizer.pt", "tokenizer.model", "pronunciations.json", "phone-vocab.json", "frontend-source.json", "training-metrics.json"):
        shutil.copy2(frontend / filename, dest / "frontend")
    shutil.copy2(Path(__file__).resolve().parents[1] / "LICENSE", dest)
    dataset_id = dataset.removeprefix("https://huggingface.co/datasets/")
    lines = ["---", "license: apache-2.0", f"language: [{language}]", "pipeline_tag: text-to-speech", "datasets:",
             f"- {dataset_id}", "---", "", f"# {name} Voice · compact browser TTS", "",
             f"Single-voice {name} speech at 24 kHz. Adapted from [Tiny Voca](https://github.com/n4ze3m/tiny-voca), using the accepted compact Bengali architecture with its learned waveform residual.",
             "", "| Quantization | Browser model bytes | Validation predicted MOS | Test predicted MOS | Test CER |",
             "| --- | ---: | ---: | ---: | ---: |", *variant_lines, "",
             "The model size includes the compressed graph, packed weights and unpacker. The shared runtime and language frontend download separately. UTMOSv2 uses 24 held-out clips and seeds 17, 29 and 43 per split. Independent ASR CER is based on 72 held-out clips where available. Each variant's `test/cer.json` identifies the recognizer. The scores include recognizer error and use the language-specific test split.",
             "", "The top-scoring variant's FP32 source is included for further training. INT6 uses calibrated 6-bit values with selected sensitive tensors kept at 8 bits.",
             "", "## Training data", "", f"Trained on [{dataset_id}]({dataset_commit}). The 20-hour synthetic corpus was generated by [Maya 2 Native](https://huggingface.co/maya-research/maya2-native) with the built-in {info['speaker']} voice. See the dataset card for text-source attribution and licensing.",
             "", "```bibtex", f"@misc{{hansda{language}maya2tts,", "  author = {Hansda, Tamal},", f"  title = {{{name} synthetic speech from Maya 2 Native}},", "  year = {2026},", f"  url = {{{dataset}}}", "}", "```", "",
             "The tokenizer was trained on the dataset's training transcripts. The recurrent phonemizer was trained using eSpeak NG pronunciation labels. Browser inference uses the shipped learned phonemizer and lexicon.", ""]
    (dest / "README.md").write_text("\n".join(lines))
    repo = f"Hansda/{name.lower()}-voice-compact"
    api.create_repo(repo, private=False, exist_ok=True)
    commit = api.upload_folder(repo_id=repo, folder_path=dest, commit_message=f"Publish compact {name} voice and held-out metrics")
    published = set(api.list_repo_files(repo, revision=commit.oid))
    if not all(path.relative_to(dest).as_posix() in published for path in dest.rglob("*") if path.is_file()):
        raise RuntimeError("The model upload is missing files")
    print(commit.commit_url, flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release", type=Path)
    parser.add_argument("dataset_commit")
    parser.add_argument("frontend", type=Path)
    parser.add_argument("dest", type=Path)
    parser.add_argument("candidates", type=Path, nargs="+")
    args = parser.parse_args()
    collect(args.release, args.dataset_commit, args.frontend, args.candidates, args.dest)
